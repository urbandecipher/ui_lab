"""U63–U66 互動測試。用法：python tests/new_components.py dist/ui-lab-minimal.html"""
import sys, asyncio, pathlib
from playwright.async_api import async_playwright
PAGE = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else 'dist/ui-lab-minimal.html').resolve().as_uri()
results = []
def check(name, cond, detail=''):
    results.append(cond); print(('✓ ' if cond else '✗ ') + name + ('' if cond else '  → ' + str(detail)))

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); pg = await b.new_page(viewport={'width': 1280, 'height': 900})
        errors = []; pg.on('pageerror', lambda e: errors.append(str(e)))
        await pg.goto(PAGE); await pg.wait_for_timeout(300)
        C = lambda n, s='': f'#{n} {s}'.strip()
        # U63
        ph = C('u63-input-mask', '[data-mask=phone] input'); idf = C('u63-input-mask', '[data-mask=tw-id] input')
        await pg.click(ph); await pg.keyboard.type('0912345678')
        check('U63 手機自動加分隔', await pg.input_value(ph) == '0912-345-678', await pg.input_value(ph))
        await pg.keyboard.press('Home'); [await pg.keyboard.press('ArrowRight') for _ in range(5)]
        await pg.keyboard.press('Backspace')
        v = await pg.input_value(ph); caret = await pg.evaluate(f"document.querySelector('{ph}').selectionStart")
        check('U63 分隔符號後 Backspace 刪前一碼、游標正確', v == '0913-456-78' and caret == 3, (v, caret))
        await pg.fill(ph, ''); await pg.click(ph); await pg.keyboard.type('09a1-2b')
        check('U63 過濾非數字', await pg.input_value(ph) == '0912', await pg.input_value(ph))
        await pg.click(idf)
        check('U63 離開時提示不完整', '還差 6 碼' in await pg.text_content(C('u63-input-mask', '[data-mask=phone] .field-msg')))
        await pg.keyboard.type('a123456789')
        check('U63 身分證轉大寫且檢查碼通過', await pg.input_value(idf) == 'A123456789' and '正確' in await pg.text_content(C('u63-input-mask', '[data-mask=tw-id] .field-msg')))
        await pg.fill(idf, ''); await pg.click(idf); await pg.keyboard.type('A123456788')
        check('U63 檢查碼錯誤會提示', '檢查碼不符' in await pg.text_content(C('u63-input-mask', '[data-mask=tw-id] .field-msg')) and await pg.get_attribute(idf, 'aria-invalid') == 'true')
        await pg.fill(idf, ''); await pg.click(idf); await pg.keyboard.type('1A23')
        check('U63 身分證首碼必須是字母', await pg.input_value(idf) == 'A23', await pg.input_value(idf))
        # U64
        inp = C('u64-multi-select', '.ms-input')
        await pg.click(inp)
        check('U64 點擊開啟清單', await pg.get_attribute(inp, 'aria-expanded') == 'true')
        for _ in range(1): await pg.keyboard.press('ArrowDown')
        await pg.keyboard.press('Enter'); await pg.keyboard.press('ArrowDown'); await pg.keyboard.press('Enter')
        chips = await pg.locator(C('u64-multi-select', '.ms-chip')).all_inner_texts()
        check('U64 Enter 連續選取且清單保持開啟', len(chips) == 2 and await pg.get_attribute(inp, 'aria-expanded') == 'true', chips)
        await pg.keyboard.type('遊戲'); await pg.keyboard.press('Enter')
        check('U64 篩選後選取', len(await pg.locator(C('u64-multi-select', '.ms-chip')).all()) == 3)
        await pg.keyboard.press('Control+A'); await pg.keyboard.press('Delete')
        dis = await pg.locator(C('u64-multi-select', '[role=option][aria-disabled=true]')).count()
        check('U64 達上限時其餘選項停用並提示', dis == 5 and '已達上限' in await pg.text_content(C('u64-multi-select', '.ms-hint')), dis)
        await pg.keyboard.press('Backspace')
        check('U64 Backspace 移除最後一項', len(await pg.locator(C('u64-multi-select', '.ms-chip')).all()) == 2)
        await pg.keyboard.press('Escape')
        check('U64 Esc 關閉', await pg.get_attribute(inp, 'aria-expanded') == 'false')
        await pg.click(C('u64-multi-select', '.ms-x >> nth=0'))
        check('U64 × 移除並回到輸入框', len(await pg.locator(C('u64-multi-select', '.ms-chip')).all()) == 1 and await pg.evaluate("document.activeElement.classList.contains('ms-input')"))
        # U65
        vp = C('u65-infinite-scroll', '.feed-viewport')
        await pg.evaluate(f"document.querySelector('{vp}').scrollIntoView()")
        await pg.evaluate(f"(v=>v.scrollTop=v.scrollHeight)(document.querySelector('{vp}'))"); await pg.wait_for_timeout(1100)
        n = await pg.locator(C('u65-infinite-scroll', '.feed-item:not(.feed-loading)')).count()
        check('U65 捲到底自動載入下一批', n == 16, n)
        await pg.click(C('u65-infinite-scroll', '.feed-more')); await pg.wait_for_timeout(1000)
        n = await pg.locator(C('u65-infinite-scroll', '.feed-item:not(.feed-loading)')).count()
        st = await pg.text_content(C('u65-infinite-scroll', '.feed-status'))
        check('U65 載入更多直到結尾', n == 24 and '全部 24' in st and await pg.is_hidden(C('u65-infinite-scroll', '.feed-more')), (n, st))
        # U66
        h = C('u66-time-picker', '.time-seg[data-part=h]'); m = C('u66-time-picker', '.time-seg[data-part=m]')
        await pg.focus(h); await pg.keyboard.type('14')
        check('U66 輸入兩位數後跳到分', await pg.evaluate("document.activeElement.dataset.part") == 'm')
        await pg.keyboard.type('20')
        val = await pg.input_value(C('u66-time-picker', '.time-value'))
        check('U66 分鐘調整到 15 分鐘時段', val == '14:15', val)
        await pg.keyboard.press('ArrowUp'); await pg.keyboard.press('ArrowUp'); await pg.keyboard.press('ArrowUp')
        check('U66 ↑ 以 15 分鐘循環', await pg.input_value(C('u66-time-picker', '.time-value')) == '14:00')
        await pg.keyboard.press('ArrowLeft'); await pg.keyboard.press('End')
        msg = await pg.text_content(C('u66-time-picker', '.time-msg'))
        check('U66 超出時段顯示錯誤', '23:00 不在可預約時段' in msg, msg)
        await pg.keyboard.press('Backspace')
        check('U66 Backspace 清除欄位', await pg.text_content(h) == '--' and await pg.input_value(C('u66-time-picker', '.time-value')) == '')
        check('沒有執行錯誤', not errors, errors)
        await b.close()
asyncio.run(main())
sys.exit(0 if all(results) else 1)
